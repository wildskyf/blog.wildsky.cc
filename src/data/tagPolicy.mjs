export const getCanonicalTags = (lang) => new Set(tagPolicy[lang].canonical);

export const canonicalizeTags = (tags, lang) => {
  const policy = tagPolicy[lang];
  const canonical = new Set(policy.canonical);
  const normalized = [];

  for (const tag of tags) {
    const candidate = policy.aliases[tag] ?? (canonical.has(tag) ? tag : null);
    if (candidate && !normalized.includes(candidate)) normalized.push(candidate);
  }

  return normalized.slice(0, 3);
};
